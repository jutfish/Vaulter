/** Filled cells of a character as [x, y] pairs (0..2, 0..4). */
export function glyphCells(ch: string): [number, number][] {
  const g = G[ch.toUpperCase()];
  if (!g) return [];
  const out: [number, number][] = [];
  g.split('|').forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] === '#') out.push([x, y]);
  });
  return out;
}

/** Width in world px of a line of text. */
export function textWidth(line: string): number {
  return Math.max(0, line.length * ADVANCE - 1);
}
